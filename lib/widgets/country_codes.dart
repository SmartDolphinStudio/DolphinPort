/// A selectable country or region and its international dial code.
class Country {
  /// Full country or region name (English).
  final String name;

  /// International dial code without the leading "+".
  final String dialCode;

  /// ISO 3166-1 alpha-2 code.
  final String isoCode;

  const Country(this.name, this.dialCode, this.isoCode);

  /// Flag emoji derived from [isoCode] via the regional indicator symbols,
  /// so every entry has an icon without bundling image assets.
  String get flag {
    const int regionalIndicatorA = 0x1F1E6;
    const int uppercaseA = 65;
    return String.fromCharCodes(
      isoCode.toUpperCase().codeUnits.map(
        (unit) => regionalIndicatorA + unit - uppercaseA,
      ),
    );
  }
}

